import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';
const read = (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('mundo-da-bia:v1')!).state);
async function ready(page: Page) { await page.goto('/'); await expect(page.locator('canvas')).toHaveAttribute('data-ready', 'true'); }
async function create(page: Page, name: string, template: string, size = 'medium') {
  await page.locator('#map-toggle').click();
  await page.locator('#new-room-name').fill(name);
  await page.locator('#room-template').selectOption(template);
  await page.locator('#room-size').selectOption(size);
  await page.locator('#create-room').click();
}
test('cria e reorganiza cômodos, viaja com Bia e salva uma versão do projeto', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await ready(page);
  await create(page, 'Estúdio Aurora', 'studio', 'large');
  let state = await read(page);
  expect(state.room).toBe('room-3');
  const canvas = (await page.locator('canvas').boundingBox())!;
  expect(canvas.width / canvas.height).toBeCloseTo(1400 / 600, 2);
  expect(state.layout.rooms['room-3']).toMatchObject({ name: 'Estúdio Aurora', size: 'large' });
  expect(state.layout.pieces.some((p: { room: string; kind: string }) => p.room === 'room-3' && p.kind === 'desk')).toBe(true);
  await page.locator('#build-toggle').click();
  await page.locator('#map-toggle').click();
  await page.locator('#bring-selected').click();
  await page.locator('#current-room-name').fill('Estúdio da banda');
  await page.locator('#room-rename').click();
  await page.locator('#room-position').selectOption('7');
  await page.locator('#room-move').click();
  await page.screenshot({ path: 'reports/house-map.png' });
  await page.locator('#close-map').click();
  state = await read(page);
  expect(state.actors[0]).toMatchObject({ room: 'room-3' });
  expect(state.layout.rooms['room-3']).toMatchObject({ name: 'Estúdio da banda', cell: 7 });
  await page.screenshot({ path: 'reports/studio-large.png' });
  await page.reload(); await expect(page.locator('canvas')).toHaveAttribute('data-ready', 'true');
  expect(await read(page)).toEqual(state);
  await create(page, 'Cozinha do café', 'kitchen');
  await page.locator('#map-toggle').click();
  await page.locator('#project-choice').selectOption('cafe');
  await expect(page.locator('#project-description')).toContainText('cardápio');
  await page.locator('#save-project').click();
  await page.locator('#close-map').click();
  await page.locator('.home-tray summary').click();
  await expect(page.locator('#house-list option')).toHaveCount(2);
  await expect(page.locator('#house-name')).toHaveValue('Café com gatos');
  expect(errors).toEqual([]);
});
test('arraste não grava a cada movimento e cancelar mantém a posição inicial', async ({ page }) => {
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem;
    Object.assign(window, { writes: 0 });
    Storage.prototype.setItem = function (...args) { const w = window as unknown as { writes: number }; w.writes++; return original.apply(this, args); };
  });
  await ready(page);
  const box = (await page.locator('canvas').boundingBox())!;
  const xy = (x: number, y: number) => ({ x: box.x + x * box.width / 1000, y: box.y + y * box.height / 600 });
  const a = xy(520, 400), b = xy(600, 390);
  const before = await read(page);
  await page.evaluate(() => Object.assign(window, { writes: 0 }));
  await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 30 });
  expect(await page.evaluate(() => (window as unknown as { writes: number }).writes)).toBe(0);
  await page.locator('canvas').dispatchEvent('pointercancel', { pointerId: 1 }); await page.mouse.up();
  expect(await read(page)).toEqual(before);
  await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 30 }); await page.mouse.up();
  expect(await page.evaluate(() => (window as unknown as { writes: number }).writes)).toBe(2);
  const actor = (await read(page)).actors[0]!;
  expect(actor.x).toBeCloseTo(600, 3); expect(actor.y).toBeCloseTo(520, 3);
  await page.screenshot({ path: 'reports/atelier-play.png' });
});
test('arrasta do catálogo e toca no fogão para ligar, com estado persistente', async ({ page }) => {
  await ready(page); await create(page, 'Cozinha', 'kitchen');
  const box = (await page.locator('canvas').boundingBox())!;
  const xy = (x: number, y: number) => ({ x: box.x + x * box.width / 1200, y: box.y + y * box.height / 600 });
  await page.getByRole('button', { name: 'Decoração', exact: true }).click();
  const button = page.getByRole('button', { name: 'Adicionar Planta', exact: true });
  await button.scrollIntoViewIfNeeded(); const start = (await button.boundingBox())!;
  const end = xy(600, 200);
  const count = (await read(page)).layout.pieces.length;
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2); await page.mouse.down();
  await page.mouse.move(end.x, end.y, { steps: 12 }); await page.mouse.up();
  const state = await read(page);
  expect(state.layout.pieces).toHaveLength(count + 1);
  expect(state.layout.pieces.at(-1)).toMatchObject({ kind: 'plant', room: 'room-3' });
  expect(state.layout.pieces.at(-1).x).toBeCloseTo(558, 0);
  await button.focus(); await page.keyboard.press('Enter');
  expect((await read(page)).layout.pieces).toHaveLength(count + 2);
  await page.locator('#build-toggle').click();
  const stove = state.layout.pieces.find((p: { kind: string }) => p.kind === 'stove');
  const p = xy(stove.x + 50, stove.y + 50); await page.mouse.click(p.x, p.y);
  expect((await read(page)).layout.pieces.find((p: { id: number }) => p.id === stove.id).active).toBe(true);
  await page.reload(); await expect(page.locator('canvas')).toHaveAttribute('data-ready', 'true');
  expect((await read(page)).layout.pieces.find((p: { id: number }) => p.id === stove.id).active).toBe(true);
  await page.screenshot({ path: 'reports/kitchen.png' });
});
